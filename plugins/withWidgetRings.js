/**
 * Writes the progress-ring pictures the home-screen widgets draw, as Android
 * vector drawables in res/drawable:
 *
 *   widget_ring_<kind>_<theme>_<step>.xml
 *
 *   kind   steps | calories | over
 *   theme  light | dark
 *   step   0, 5, 10 … 100 (percent of the ring filled; "over" only has 100)
 *
 * Why pictures: Android widgets can't draw a progress ring themselves. The
 * built-in circular indicator came out as a small clipped arc that ignored
 * its size and sat off-centre (v0.24.0). A vector picture scales to whatever
 * cell the launcher gives and stays a full, centred circle.
 *
 * The colours match src/widgets/*Widget.tsx; change both together.
 */
const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('expo/config-plugins');

const RING_COLOURS = {
  steps: { light: '#1F9D55', dark: '#B6F24A' },
  calories: { light: '#F26A1B', dark: '#FF8A4C' },
  over: { light: '#C62828', dark: '#FF6B6B' },
};
const TRACK = { light: '#E3E7E5', dark: '#2C3430' };
const STEP = 5;
const SIZE = 100;
const STROKE = 10;
const RADIUS = (SIZE - STROKE) / 2;
const CENTRE = SIZE / 2;

const round = (n) => Math.round(n * 100) / 100;

/** A full circle as two half arcs, starting at the top. */
function circlePath() {
  const top = CENTRE - RADIUS;
  const bottom = CENTRE + RADIUS;
  return `M${CENTRE},${top} A${RADIUS},${RADIUS} 0 1,1 ${CENTRE},${bottom} A${RADIUS},${RADIUS} 0 1,1 ${CENTRE},${top}`;
}

/** An arc from 12 o'clock, clockwise, covering `percent` of the circle. */
function arcPath(percent) {
  if (percent >= 100) return circlePath();
  const angle = (percent / 100) * 2 * Math.PI;
  const x = round(CENTRE + RADIUS * Math.sin(angle));
  const y = round(CENTRE - RADIUS * Math.cos(angle));
  const largeArc = percent > 50 ? 1 : 0;
  return `M${CENTRE},${CENTRE - RADIUS} A${RADIUS},${RADIUS} 0 ${largeArc},1 ${x},${y}`;
}

function ringVectorXml(percent, colour, track) {
  const arc =
    percent > 0
      ? `
  <path
      android:pathData="${arcPath(percent)}"
      android:strokeColor="${colour}"
      android:strokeWidth="${STROKE}"
      android:strokeLineCap="round" />`
      : '';
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withWidgetRings.js. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${SIZE}dp"
    android:height="${SIZE}dp"
    android:viewportWidth="${SIZE}"
    android:viewportHeight="${SIZE}">
  <path
      android:pathData="${circlePath()}"
      android:strokeColor="${track}"
      android:strokeWidth="${STROKE}" />${arc}
</vector>
`;
}

/** Every drawable file the widgets can ask for, as { name, xml }. */
function ringDrawables() {
  const files = [];
  for (const [kind, colours] of Object.entries(RING_COLOURS)) {
    for (const theme of ['light', 'dark']) {
      const steps = kind === 'over' ? [100] : Array.from({ length: 100 / STEP + 1 }, (_, i) => i * STEP);
      for (const step of steps) {
        files.push({
          name: `widget_ring_${kind}_${theme}_${step}`,
          xml: ringVectorXml(step, colours[theme], TRACK[theme]),
        });
      }
    }
  }
  return files;
}

const withWidgetRings = (config) =>
  withDangerousMod(config, [
    'android',
    (mod) => {
      const dir = path.join(mod.modRequest.platformProjectRoot, 'app/src/main/res/drawable');
      fs.mkdirSync(dir, { recursive: true });
      for (const { name, xml } of ringDrawables()) {
        fs.writeFileSync(path.join(dir, `${name}.xml`), xml);
      }
      return mod;
    },
  ]);

module.exports = withWidgetRings;
module.exports.ringDrawables = ringDrawables;
module.exports.arcPath = arcPath;
module.exports.RING_COLOURS = RING_COLOURS;
module.exports.TRACK = TRACK;
